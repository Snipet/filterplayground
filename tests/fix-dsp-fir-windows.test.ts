describe('Welch window description', () => {
	it('end samples are 4N/(N+1)², not zero, and the description says so', () => {
		for (const N of [16, 64]) {
			const w = windowValues('welch', N);
			expect(w[0]).toBeCloseTo((4 * N) / Math.pow(N + 1, 2), 14);
			expect(w[N - 1]).toBeCloseTo(w[0], 14);
			expect(w[0]).toBeGreaterThan(0);
		}
		const desc = windowInfo('welch').description;
		expect(desc).not.toMatch(/reaching zero at the ends/);
		expect(desc).toMatch(/not zero/);
		// the value quoted in the text
		expect(desc).toMatch(/0\.22 at N = 16/);
		expect(windowValues('welch', 16)[0]).toBeCloseTo(0.22, 2);
	});
	it('the parabola reaches zero one sample beyond each end', () => {
		// w(n) = 1 − ((n − M/2)/(M/2 + 1))², M = N − 1, extended to n = −1 and n = N
		const N = 16;
		const M = N - 1;
		const w = (n: number) => 1 - Math.pow((n - M / 2) / (M / 2 + 1), 2);
		const vals = windowValues('welch', N);
		vals.forEach((v, n) => expect(v).toBeCloseTo(w(n), 14));
		expect(w(-1)).toBeCloseTo(0, 14);
		expect(w(N)).toBeCloseTo(0, 14);
	});
});
